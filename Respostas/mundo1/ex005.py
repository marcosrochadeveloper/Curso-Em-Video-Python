# Ex005 - Faça um programa que leia um número inteiro e mostre na tela o seu sucessor e seu antecessor.
# [Exemplo] A EXECUÇÃO DO PROGRAMA SERÁ COMO MOSTRADO ABAIXO:
# Digite um número: 5
# Analisando o valor 5, seu antecessor é 4 e o sucessor é 6!

num = int(input('Digite um número: '))
print(f'Analisando o valor {num} seu antecessor é {num - 1} e o sucessor é {num + 1}!')